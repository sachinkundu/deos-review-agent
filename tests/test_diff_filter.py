        ("src/third-party/client.py", "vendored", "vendored-path-segment:third-party"),
        ("web/dist/app.js", "generated", "generated-path-segment:dist"),
        ("proto/message_pb2.py", "generated", "generated-filename:*_pb2.py"),
        ("web/app.min.css", "generated", "generated-filename:*.min.css"),
