def test_classify_metadata_uses_fixed_precedence_and_rules(path: str, category: str, rule: str):
    exclusion = classify_metadata(path)
    assert exclusion is not None
    assert exclusion.path == path
    assert exclusion.category == category
    assert exclusion.rule == rule


